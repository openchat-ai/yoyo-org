import os
# Write test.ky with proper yoy-ty format
# 0x40 = '@' = 64 = "40" in hex, 0x30 = '0' = 48, etc.
content = bytes([
    0x30, 0x30, 0x20, 0x30, 0x30, 0x20, 0x40, 0x30, 0x20, 0x30, 0x30, 0x0A,  # "00 00 40 00\n"
    0x30, 0x30, 0x20, 0x30, 0x30, 0x20, 0x33, 0x30, 0x20, 0x30, 0x45, 0x20, 0x30, 0x30, 0x0A,  # "00 00 30 0E 00\n"
    0x30, 0x30, 0x20, 0x30, 0x30, 0x20, 0x33, 0x30, 0x20, 0x31, 0x30, 0x20, 0x30, 0x30, 0x0A,  # "00 00 30 10 00\n"
    0x30, 0x30, 0x20, 0x30, 0x30, 0x20, 0x33, 0x30, 0x20, 0x31, 0x31, 0x20, 0x30, 0x30, 0x0A,  # "00 00 30 11 00\n"
    0x30, 0x30, 0x20, 0x30, 0x30, 0x20, 0x46, 0x46, 0x0A,  # "00 00 FF\n"
])
with open(r'F:\yoyo-org\yoyo-asm\test.ky', 'wb') as f:
    f.write(content)
print(f'wrote {len(content)} bytes')
d = open(r'F:\yoyo-org\yoyo-asm\test.ky', 'rb').read()
print(f'file size: {len(d)}')
# Show first 15 bytes
for i in range(min(15, len(d))):
    b = d[i]
    c = chr(b) if 32 <= b < 127 else '.'
    print(f'  {i:3d}: 0x{b:02x} ({c})')
